'use strict';

// Generate the tap formula from the tagged manifest and the public release
// archives. Homebrew installs these exact bytes; it does not rebuild them.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const { binsFromManifest } = require('../npm/platform');

function stableVersion(version) {
  if (typeof version !== 'string' || version.trim() !== version ||
      !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version)) {
    throw new Error('Expected a stable release version X.Y.Z');
  }
  return version.split('.').map(BigInt);
}

function newer(a, b) {
  const left = stableVersion(a);
  const right = stableVersion(b);
  for (let i = 0; i < 3; i++) {
    if (left[i] !== right[i]) return left[i] > right[i];
  }
  return false;
}

function archiveChecksum(artifacts, version, target, bins) {
  const name = `opscope-v${version}-${target}.tar.gz`;
  const file = path.join(artifacts, name);
  const hash = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
  const recorded = fs.readFileSync(`${file}.sha256`, 'utf8').trim();
  if (recorded !== `${hash}  ${name}`) throw new Error(`Checksum mismatch for ${name}`);
  const listed = spawnSync('tar', ['-tzf', file], { encoding: 'utf8' });
  if (listed.status !== 0) throw new Error(`Cannot list ${name}: ${listed.stderr}`);
  const entries = new Set(listed.stdout.trim().split('\n'));
  const root = name.replace(/\.tar\.gz$/, '');
  for (const bin of bins) {
    if (!entries.has(`${root}/${bin}`)) throw new Error(`${name} is missing binary ${bin}`);
  }
  return hash;
}

function generateFormula(version, artifacts, repoRoot = path.resolve(__dirname, '..')) {
  stableVersion(version);
  const bins = binsFromManifest(repoRoot);
  const arm = archiveChecksum(artifacts, version, 'aarch64-apple-darwin', bins);
  const intel = archiveChecksum(artifacts, version, 'x86_64-apple-darwin', bins);
  return `# Generated by opscope's homebrew/formula.js from the published release.
# Release: ${version}
class Opscope < Formula
  desc "Terminal widgets showing real operational data"
  homepage "https://github.com/stealth-factory/opscope"
  license "AGPL-3.0-or-later"

  depends_on :macos

  on_macos do
    on_arm do
      url "https://github.com/stealth-factory/opscope/releases/download/v${version}/opscope-v${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${arm}"
    end
    on_intel do
      url "https://github.com/stealth-factory/opscope/releases/download/v${version}/opscope-v${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${intel}"
    end
  end

  # Keep every widget beside the launcher, without shadowing tools on PATH.
  BINARY_NAMES = %w[
${bins.map(bin => `    ${bin}`).join('\n')}
  ].freeze

  def install
    BINARY_NAMES.each { |name| libexec.install name }
    pkgshare.install "docs", "widgets", "README.md", "LICENSE", "config.example.json"
    bin.write_exec_script libexec/"opscope"
  end

  def caveats
    <<~EOS
      Start the menu with opscope, or a widget with opscope clocks.
      Check optional external tools with opscope doctor.
      Settings are saved in ~/.config/opscope/config.json (or OPSCOPE_CONFIG).
      Example configuration and documentation: #{pkgshare}
    EOS
  end

  test do
    assert_equal ["opscope"], bin.children.map { |file| file.basename.to_s }
    BINARY_NAMES.each do |name|
      assert_match "#{name} #{version}", shell_output("#{libexec}/#{name} --version")
    end
    assert_match "Clocks:", shell_output("#{bin}/opscope clocks --help")
  end
end
`;
}

if (require.main === module) {
  const [version, artifacts, output, previous] = process.argv.slice(2);
  if (!version || !artifacts || !output) {
    throw new Error('Usage: node homebrew/formula.js VERSION ARTIFACTS OUTPUT [PREVIOUS_FORMULA]');
  }
  stableVersion(version);
  if (previous) {
    const match = fs.readFileSync(previous, 'utf8').match(/^# Release: ([^\n]+)$/m);
    if (!match) throw new Error('Existing opscope formula has no release marker');
    if (newer(match[1], version)) {
      console.log(`Tap already has ${match[1]}; refusing to downgrade to ${version}`);
      process.exit(0);
    }
  }
  const generated = generateFormula(version, artifacts);
  if (previous) {
    const original = fs.readFileSync(previous, 'utf8');
    const sameVersion = original.includes(`# Release: ${version}\n`);
    if (sameVersion && original !== generated) {
      throw new Error('This version already has a different formula; refusing to replace it');
    }
  }
  fs.writeFileSync(output, generated);
}

module.exports = { generateFormula, stableVersion, newer };
